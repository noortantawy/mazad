// Run: node scripts/generate-seed.mjs
// Writes: public/seed/*.svg, lib/seed-items.json, supabase/seed_auctions.sql, supabase/seed_demo_bids.sql
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ICONS, ITEMS } from "./seed-items.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const picsDir = join(root, "public", "seed");
mkdirSync(picsDir, { recursive: true });

const BIDDERS = [
  ["Omar", "omar.demo@mazad.test"],
  ["Mona", "mona.demo@mazad.test"],
  ["Karim", "karim.demo@mazad.test"],
  ["Salma", "salma.demo@mazad.test"],
  ["Youssef", "youssef.demo@mazad.test"],
];

// ---------- pictures ----------
function svg(item, n) {
  const icon = ICONS[item.cat] ?? ICONS.other;
  const angle = [135, 35, 215][n % 3];
  const rad = (angle * Math.PI) / 180;
  const x2 = 50 + 50 * Math.cos(rad), y2 = 50 + 50 * Math.sin(rad);
  const gid = `g${n}`;
  const circles = [
    `<circle cx="660" cy="110" r="190" fill="#fff" fill-opacity=".08"/><circle cx="120" cy="520" r="150" fill="#000" fill-opacity=".12"/>`,
    `<circle cx="150" cy="120" r="170" fill="#fff" fill-opacity=".09"/><circle cx="700" cy="500" r="210" fill="#000" fill-opacity=".1"/>`,
    `<rect x="-60" y="380" width="920" height="260" fill="#000" fill-opacity=".14" transform="rotate(-6 400 500)"/><circle cx="640" cy="130" r="120" fill="#fff" fill-opacity=".1"/>`,
  ][n % 3];
  const scale = [11, 8.5, 10][n % 3];
  const tx = 400 - 12 * scale + [0, -90, 40][n % 3];
  const ty = 300 - 12 * scale + [0, 10, -10][n % 3];
  const ring = n % 3 === 2 ? `<circle cx="${400 + 40}" cy="${300 - 10}" r="${12 * scale + 36}" fill="none" stroke="#fff" stroke-opacity=".35" stroke-width="3"/>` : "";
  const grid = n % 3 === 1
    ? `<g stroke="#fff" stroke-opacity=".08">${Array.from({ length: 10 }, (_, i) => `<path d="M${i * 90} 0V600"/>`).join("")}${Array.from({ length: 7 }, (_, i) => `<path d="M0 ${i * 90}H800"/>`).join("")}</g>`
    : "";
  const label = item.title.replace(/&/g, "&amp;").replace(/</g, "&lt;");
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 600" role="img" aria-label="${label}">
<defs><linearGradient id="${gid}" x1="${100 - x2}%" y1="${100 - y2}%" x2="${x2}%" y2="${y2}%"><stop offset="0" stop-color="${item.c1}"/><stop offset="1" stop-color="${item.c2}"/></linearGradient></defs>
<rect width="800" height="600" fill="url(#${gid})"/>
${grid}${circles}${ring}
<g transform="translate(${tx} ${ty}) scale(${scale})" fill="none" stroke="#fff" stroke-opacity=".92" stroke-width="1.4" stroke-linecap="round" stroke-linejoin="round"><path d="${icon}"/></g>
</svg>
`;
}

// ---------- bid ladders ----------
function ladder(it) {
  if (!it.bids) return [];
  const out = [];
  for (let i = 1; i <= it.bids; i++) {
    const t = i / it.bids;
    let v = Math.round((it.start + (it.current - it.start) * Math.pow(t, 1.15)) / 5) * 5;
    if (i === 1) v = it.start;
    if (i === it.bids) v = it.current;
    const prev = out[out.length - 1];
    if (prev !== undefined && v <= prev) v = prev + 5;
    out.push(v);
  }
  out[out.length - 1] = it.current;
  return out;
}

const items = ITEMS.map((it) => {
  const images = Array.from({ length: it.pics }, (_, i) => {
    const file = `${it.slug}-${i + 1}.svg`;
    writeFileSync(join(picsDir, file), svg(it, i));
    return `/seed/${file}`;
  });
  return { ...it, images, ladder: ladder(it) };
});

writeFileSync(join(root, "lib", "seed-items.json"), JSON.stringify(items, null, 2) + "\n");

// ---------- SQL ----------
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const hoursSql = (h) => (h == null ? "null" : `now() + interval '${Math.round(h * 60)} minutes'`);

const auctionRows = items.map((it) => {
  const start = it.open ? 1 : it.start;
  const dep = Math.round(start) * 0.01;
  return `    (${q(it.title)}, ${q(it.desc)}, ${q(it.cat)}, array[${it.images.map(q).join(", ")}], ${q(it.cond)}, ${q(it.city)}, ${start}, ${it.open ? "true" : "false"}, ${it.reserve ?? "null"}, ${q(it.endsInH == null ? "open_ended" : "timed")}, ${hoursSql(it.endsInH)}, ${dep.toFixed(2)})`;
});

writeFileSync(
  join(root, "supabase", "seed_auctions.sql"),
  `-- Sample auctions with pictures. Generated by scripts/generate-seed.mjs; do not edit by hand.
-- Prerequisite: run 0001_schema.sql and seed.sql, then sign up once in the app.
-- The first account becomes the seller of these listings. Safe to run again (skips titles that exist).
-- Pictures are served from /public/seed on your own site, so deploy the app before expecting them to show.

do $$
declare seller uuid;
begin
  select id into seller from public.profiles order by created_at limit 1;
  if seller is null then
    raise exception 'Sign up in the app first so there is a seller account, then run this again.';
  end if;

  insert into public.auctions
    (seller_id, category_id, title, description, images, condition, city, start_price, open_to_highest,
     reserve_price, mode, ends_at, current_price, deposit_amount)
  select seller, c.id, v.title, v.description, v.images, v.condition, v.city, v.start_price, v.open_to_highest,
         v.reserve, v.mode::auction_mode, v.ends_at, v.start_price, v.deposit
  from (values
${auctionRows.join(",\n")}
  ) as v(title, description, cat, images, condition, city, start_price, open_to_highest, reserve, mode, ends_at, deposit)
  join public.categories c on c.slug = v.cat
  where not exists (select 1 from public.auctions a where a.seller_id = seller and a.title = v.title);
end $$;
`,
);

// Demo bids: needs fake bidder accounts in auth.users (the trigger creates their profiles).
const bidderValues = BIDDERS.map(([n, e]) => `    (${q(n)}, ${q(e)})`).join(",\n");
const bidRows = [];
items.forEach((it) => {
  const n = it.ladder.length;
  it.ladder.forEach((amount, i) => {
    const minutesAgo = (n - i) * 17;
    bidRows.push(`    (${q(it.title)}, ${i % BIDDERS.length}, ${amount}, ${minutesAgo})`);
  });
});

writeFileSync(
  join(root, "supabase", "seed_demo_bids.sql"),
  `-- OPTIONAL: fake bidders and a realistic bid history on the sample auctions.
-- Generated by scripts/generate-seed.mjs; do not edit by hand. Run after seed_auctions.sql.
-- It inserts 5 demo users directly into auth.users (password-less, they cannot sign in), gives each a
-- test wallet, then replays bids so prices, bid counts, held deposits and wallets all agree.
-- Delete the demo data later with: delete from auth.users where email like '%.demo@mazad.test';

do $$
declare
  bidder_ids uuid[] := '{}';
  b record;
  new_id uuid;
  r record;
begin
  if exists (select 1 from auth.users where email like '%.demo@mazad.test') then
    raise notice 'Demo bidders already exist, nothing to do.';
    return;
  end if;

  for b in select * from (values
${bidderValues}
  ) as t(name, email) loop
    new_id := gen_random_uuid();
    insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
                            raw_app_meta_data, raw_user_meta_data, created_at, updated_at)
    values ('00000000-0000-0000-0000-000000000000', new_id, 'authenticated', 'authenticated', b.email, '', now(),
            '{"provider":"email","providers":["email"]}', jsonb_build_object('name', b.name), now(), now());
    bidder_ids := bidder_ids || new_id;
  end loop;

  update public.profiles set wallet_balance = 100000 where id = any(bidder_ids);

  for r in select * from (values
${bidRows.join(",\n")}
  ) as t(title, bidder, amount, minutes_ago) loop
    declare
      a public.auctions%rowtype;
      uid uuid := bidder_ids[r.bidder + 1];
    begin
      select * into a from public.auctions where title = r.title order by created_at limit 1;
      continue when not found;

      insert into public.deposits (auction_id, user_id, amount)
      values (a.id, uid, a.deposit_amount) on conflict do nothing;

      insert into public.bids (auction_id, bidder_id, amount, created_at)
      values (a.id, uid, r.amount, now() - make_interval(mins => r.minutes_ago));

      update public.auctions set current_price = r.amount, bid_count = bid_count + 1 where id = a.id;
    end;
  end loop;

  -- Recompute wallets from the deposits we just created.
  update public.profiles p set
    wallet_held = coalesce((select sum(d.amount) from public.deposits d where d.user_id = p.id and d.status = 'held'), 0),
    wallet_balance = 100000 - coalesce((select sum(d.amount) from public.deposits d where d.user_id = p.id and d.status = 'held'), 0)
  where p.id = any(bidder_ids);

  insert into public.wallet_tx (user_id, type, amount, ref)
  select d.user_id, 'hold', d.amount, d.auction_id from public.deposits d where d.user_id = any(bidder_ids);
end $$;
`,
);

