// Generated by scripts/generate-seed.mjs from scripts/seed-items.mjs.
type SeedItem = {
  slug: string; title: string; cat: string; start: number; current: number; bids: number;
  endsInH: number | null; city: string; cond: Auction["condition"]; open?: boolean; reserve?: number;
  desc: string; images: string[]; ladder: number[];
};
const SEEDS = seedItems as SeedItem[];

const H = 3600_000;
const now = Date.now();
const iso = (ms: number) => new Date(now + ms).toISOString();
const BIDDER_NAMES = ["Omar", "Mona", "Karim", "Salma", "Youssef"];

export const DEMO_AUCTIONS: Auction[] = SEEDS.map((s, i) => {
  const start = s.open ? 1 : s.start;
  return {
    id: `demo-${i + 1}`,
    seller_id: "demo-seller",
    category_id: DEMO_CATEGORIES.find((c) => c.slug === s.cat)?.id ?? 10,
    title: s.title,
    description: s.desc,
    images: s.images,
    condition: s.cond,
    city: s.city,
    start_price: start,
    open_to_highest: Boolean(s.open),
    has_reserve: s.reserve != null,
    mode: s.endsInH == null ? "open_ended" : "timed",
    ends_at: s.endsInH == null ? null : iso(s.endsInH * H),
    status: "live",
    current_price: s.bids ? s.current : start,
    bid_count: s.bids,
    winner_id: null,
    deposit_amount: Math.round(start * 0.01 * 100) / 100,
    created_at: iso(-(i + 1) * 2 * H),
    trend_score: s.bids * 3 + (i % 4) * 2,
  };
});

export function demoBids(auctionId: string): Bid[] {
  const idx = DEMO_AUCTIONS.findIndex((x) => x.id === auctionId);
  if (idx < 0) return [];
  const ladder = SEEDS[idx].ladder;
  // Highest first, like the real query.
  return ladder
    .map((amount, i) => ({
      id: i,
      auction_id: auctionId,
      bidder_id: `demo-bidder-${i % BIDDER_NAMES.length}`,
      amount,
      created_at: iso(-(ladder.length - i) * 17 * 60_000),
      bidder_name: BIDDER_NAMES[i % BIDDER_NAMES.length],
    }))
    .reverse()
    .slice(0, 20);
}
